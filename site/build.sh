#!/usr/bin/env bash
# Assembles the GitHub Pages site into _site/ (or the directory given).
# Run from the repository root: site/build.sh [outdir]
#
# Nothing on the page is retyped from the code:
# - The bow-tie explorer is rendered by spoor itself. Neovim runs site/bowtie.lua, which asks
#   gopls for call hierarchy on tests/fixtures/go (the demo's synthetic shop repo) and lays every
#   bow-tie out with lua/spoor/render.lua. Needs nvim 0.11+ and gopls (GOPLS=/path overrides).
# - The configuration block is cut from lua/spoor/config.lua, the release notes from CHANGELOG.md
#   and the version from the latest tag.
# - The recording and its stills come from demo/demo.gif through ffmpeg; without ffmpeg the page
#   shows the GIF itself.
set -euo pipefail
out=${1:-_site}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

rm -rf "$out"
mkdir -p "$out"
cp site/index.html site/style.css site/app.js site/favicon.svg site/og.png \
   site/404.html site/robots.txt site/sitemap.xml "$out"/
cp demo/demo.gif "$out"/demo.gif

# The explorer: spoor + gopls on the fixture, with throwaway Neovim state.
gopls=${GOPLS:-$(command -v gopls || echo "$(go env GOPATH 2>/dev/null || echo "$HOME/go")/bin/gopls")}
test -x "$gopls" || { echo "gopls not found (set GOPLS=/path/to/gopls)" >&2; exit 1; }
XDG_STATE_HOME="$tmp/state" XDG_DATA_HOME="$tmp/data" XDG_CACHE_HOME="$tmp/cache" \
  nvim --headless --clean -l site/bowtie.lua "$gopls" "$tmp/bowtie.json"
python3 -m json.tool "$tmp/bowtie.json" >/dev/null
# Fail closed if an absolute path of this machine slipped into the data.
if grep -qF -e "$PWD" -e "$HOME/" "$tmp/bowtie.json"; then
  echo "bowtie.json contains a local path; refusing to publish it" >&2
  exit 1
fi
{
  printf '// Generated by site/build.sh: gopls on tests/fixtures/go, laid out by spoor'"'"'s render.lua.\n'
  printf 'window.SPOOR_BOWTIE = '
  cat "$tmp/bowtie.json"
  printf ';\n'
} >"$out/bowtie.js"

# Defaults from config.lua, release notes from CHANGELOG.md, the no-script bow-tie.
python3 - "$out/index.html" "$tmp/bowtie.json" <<'PY'
import html, json, re, sys

page_path, bowtie_path = sys.argv[1], sys.argv[2]
page = open(page_path, encoding="utf-8").read()

def put(marker, content):
    global page
    pattern = re.compile(r"<!--%s-->.*?<!--/%s-->" % (marker, marker), re.S)
    assert pattern.search(page), "marker %s missing in index.html" % marker
    page = pattern.sub(lambda _: content, page, count=1)

# config.lua: M.defaults = { ... } up to the closing brace. The icons table holds Nerd Font
# glyphs a browser can't draw without that font, so it is folded to one line (as the README does).
src = open("lua/spoor/config.lua", encoding="utf-8").read()
block = re.search(r"^M\.defaults = (\{\n.*?\n\})\n", src, re.S | re.M).group(1)
block = re.sub(r"\n  icons = \{\n.*?\n  \},", "\n  icons = { ... }, -- Nerd Font glyphs; see lua/spoor/config.lua", block, flags=re.S)
put("config", html.escape(block))

# CHANGELOG.md: each release's first point, first sentence or two.
def inline(md):
    md = html.escape(md, quote=False)
    md = re.sub(r"`([^`]+)`", r"<code>\1</code>", md)
    md = re.sub(r"\*([^*]+)\*", r"<em>\1</em>", md)
    return md

rows = []
for m in re.finditer(r"^## (\S+) - (\d{4}-\d{2}-\d{2})\n\n(.*?)(?=^## |\Z)", open("CHANGELOG.md", encoding="utf-8").read(), re.S | re.M):
    version, date, body = m.groups()
    bullets = [b.strip() for b in re.split(r"^- ", body, flags=re.M) if b.strip()]
    lead = ""
    if bullets and not body.lstrip().startswith("- "):  # a line before the list ("First release.")
        lead = bullets.pop(0).rstrip(".") + ". "
    text = " ".join(bullets[0].split())
    sentences = re.split(r"(?<=[.!?])\s+(?=[A-Z`*(])", text)
    summary = lead + sentences[0]
    if len(summary) < 90 and len(sentences) > 1:
        summary += " " + sentences[1]
    tag = "v" + version
    rows.append(
        '<li><a class="rel-v" href="https://github.com/Matthew-Eucaristo/spoor.nvim/releases/tag/%s">%s</a>'
        '<time datetime="%s">%s</time><p>%s</p><span class="rel-more">%d %s</span></li>'
        % (tag, tag, date, date, inline(summary), len(bullets), "change" if len(bullets) == 1 else "changes")
    )
put("changelog", "\n".join(rows))

# Without script, the explorer shows its first bow-tie as plain text.
data = json.load(open(bowtie_path, encoding="utf-8"))
view = data["views"][data["start"]]["widths"]["84"]
plain = "\n".join("".join(s[0] for s in line) for line in view["lines"])
plain = re.sub("[-\U000f0000-\U000ffffd]", "ƒ", plain)
put("bowtie", html.escape(plain))

open(page_path, "w", encoding="utf-8").write(page)
PY

# Latest release tag, when tags are available (CI fetches them).
if tag=$(git describe --tags --abbrev=0 2>/dev/null); then
  sed -i.bak "s|<!--version-->[^<]*<!--/version-->|$tag|g" "$out/index.html" && rm -f "$out/index.html.bak"
fi

# The recording, and stills of the moments the page talks about (seconds into demo.gif).
stills="stage-focus:4 stage-neighbours:27.5 stage-follow:43.5 stage-note:50 card:12.5 panel:15 changes:57.5 pinned:37"
if command -v ffmpeg >/dev/null; then
  ffmpeg -loglevel error -y -i demo/demo.gif -movflags +faststart -pix_fmt yuv420p \
    -vf "scale=trunc(iw/2)*2:trunc(ih/2)*2" -c:v libx264 -crf 26 -preset slow "$out/demo.mp4"
  # WebP when this ffmpeg has the encoder (Ubuntu's does), else PNG (flat terminal colours compress well).
  if ffmpeg -hide_banner -encoders 2>/dev/null | grep -q libwebp; then still=(-c:v libwebp -quality 80) ext=webp
  else still=(-c:v png -compression_level 9) ext=png
    sed -i.bak -E 's/"(stage-[a-z]+|card|panel|changes|pinned)\.webp"/"\1.png"/g' "$out/index.html" && rm -f "$out/index.html.bak"
  fi
  for s in $stills; do
    ffmpeg -loglevel error -y -i demo/demo.gif -ss "${s#*:}" -frames:v 1 "${still[@]}" "$out/${s%%:*}.$ext"
  done
else
  echo "ffmpeg not found: the page will show demo.gif for the recording and its stills" >&2
  sed -i.bak -E 's/"(stage-[a-z]+|card|panel|changes|pinned)\.webp"/"demo.gif"/g' "$out/index.html" && rm -f "$out/index.html.bak"
fi
ls -la "$out"
